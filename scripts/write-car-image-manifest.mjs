import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const projectRoot = fileURLToPath(new URL('../', import.meta.url));
export async function listCarImages(root = projectRoot) {
  const directory = path.join(root, 'assets/List_Car');
  await mkdir(directory, { recursive: true });
  const normalize = (value) =>
    value
      .normalize('NFKD')
      .toLowerCase()
      .replace(/[^a-z0-9]/g, '');
  const entries = [];
  for (const folder of await readdir(directory, { withFileTypes: true })) {
    if (!folder.isDirectory()) continue;
    const brand = normalize(folder.name);
    for (const filename of await readdir(path.join(directory, folder.name))) {
      if (!/\.(png|jpe?g|webp|avif)$/i.test(filename)) continue;
      let name = filename.replace(/\.[^.]+$/, '');
      const year = name.match(/(?:\s|_|-)((?:19|20)\d{2})$/);
      if (year) name = name.slice(0, year.index);
      if (
        normalize(name).startsWith(brand) &&
        name.toLowerCase().startsWith(folder.name.toLowerCase() + ' ')
      )
        name = name.slice(folder.name.length).trim();
      // Explicit filename spelling supplied in this collection; no fuzzy model matching.
      const model = brand === 'haval' && normalize(name) === 'dargon' ? 'dargo' : normalize(name);
      const version = createHash('sha256')
        .update(await readFile(path.join(directory, folder.name, filename)))
        .digest('hex')
        .slice(0, 12);
      entries.push({
        brandId: ({ gwm: 'great-wall', greatwall: 'great-wall', mercedesbenz: 'mercedes-benz' })[brand] ?? brand,
        model,
        year: year ? Number(year[1]) : null,
        url:
          'assets/List_Car/' +
          [folder.name, filename].map(encodeURIComponent).join('/') +
          '?v=' +
          version,
      });
    }
  }
  entries.sort((a, b) => a.url.localeCompare(b.url, 'en'));
  return entries;
}

export async function writeCarImageManifest({ root = projectRoot } = {}) {
  const entries = await listCarImages(root);
  const target = path.join(root, 'src/app/core/catalog/car-image-manifest.ts');
  const content =
    '// Generated by scripts/write-car-image-manifest.mjs from assets/List_Car.\nexport interface CarImageEntry { readonly brandId: string; readonly model: string; readonly year: number | null; readonly url: string; }\nexport const carImageManifest: readonly CarImageEntry[] = ' +
    JSON.stringify(entries, null, 2) +
    ';\n';
  let previous;
  try {
    previous = await readFile(target, 'utf8');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  const changed = previous !== content;
  if (changed) {
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, content);
  }
  return { changed, count: entries.length };
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  const result = await writeCarImageManifest();
  console.log(`Indexed ${result.count} car images${result.changed ? '' : ' (unchanged)'}.`);
}
